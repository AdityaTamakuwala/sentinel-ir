#!/usr/bin/env python3
"""Deterministic OpenAPI 3.1 exporter and TypeScript SDK generator for SENTINEL IR.

Usage:
  python scripts/generate_openapi_client.py          # Regenerate openapi.json + generated.ts
  python scripts/generate_openapi_client.py --check  # Fail with exit code 1 if drift detected
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
BACKEND_DIR = ROOT / "backend"
sys.path.insert(0, str(BACKEND_DIR))

os.environ.setdefault("APP_ENV", "development")

from app.main import create_app  # noqa: E402

OPENAPI_OUT = ROOT / "frontend" / "src" / "lib" / "api" / "openapi.json"
TS_OUT = ROOT / "frontend" / "src" / "lib" / "api" / "generated.ts"


def _sanitize_ts_identifier(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if cleaned and cleaned[0].isdigit():
        cleaned = f"_{cleaned}"
    return cleaned


def _schema_to_ts(schema: dict[str, Any] | bool, schemas: dict[str, Any], indent: int = 0) -> str:
    if isinstance(schema, bool):
        return "unknown" if schema else "never"

    if "$ref" in schema:
        ref_name = schema["$ref"].split("/")[-1]
        return _sanitize_ts_identifier(ref_name)

    if "anyOf" in schema:
        variants = [_schema_to_ts(sub, schemas, indent) for sub in schema["anyOf"]]
        deduped = list(dict.fromkeys(variants))
        return " | ".join(deduped) if deduped else "unknown"

    if "oneOf" in schema:
        variants = [_schema_to_ts(sub, schemas, indent) for sub in schema["oneOf"]]
        deduped = list(dict.fromkeys(variants))
        return " | ".join(deduped) if deduped else "unknown"

    if "enum" in schema:
        vals = schema["enum"]
        rendered = []
        for v in vals:
            if isinstance(v, str):
                rendered.append(json.dumps(v))
            elif v is None:
                rendered.append("null")
            else:
                rendered.append(str(v))
        return " | ".join(rendered) if rendered else "string"

    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        parts = []
        for st in schema_type:
            if st == "null":
                parts.append("null")
            else:
                sub_copy = dict(schema)
                sub_copy["type"] = st
                parts.append(_schema_to_ts(sub_copy, schemas, indent))
        return " | ".join(dict.fromkeys(parts))

    if schema_type == "string":
        return "string"
    if schema_type in ("integer", "number"):
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"
    if schema_type == "array":
        item_ts = _schema_to_ts(schema.get("items", {}), schemas, indent)
        return f"Array<{item_ts}>"

    if schema_type == "object" or "properties" in schema or "additionalProperties" in schema:
        props: dict[str, Any] = schema.get("properties", {})
        required_set = set(schema.get("required", []))
        add_props = schema.get("additionalProperties")

        if not props:
            if isinstance(add_props, dict):
                val_ts = _schema_to_ts(add_props, schemas, indent)
                return f"Record<string, {val_ts}>"
            return "Record<string, any>"

        pad = "  " * (indent + 1)
        close_pad = "  " * indent
        lines = ["{"]
        for prop_name in sorted(props.keys()):
            prop_schema = props[prop_name]
            opt = "" if prop_name in required_set else "?"
            prop_ts = _schema_to_ts(prop_schema, schemas, indent + 1)
            safe_key = (
                prop_name
                if re.match(r"^[A-Za-z_$][A-Za-z0-9_$]*$", prop_name)
                else json.dumps(prop_name)
            )
            lines.append(f"{pad}{safe_key}{opt}: {prop_ts};")
        lines.append(f"{close_pad}}}")
        return "\n".join(lines)

    return "any"


def render_typescript_sdk(spec: dict[str, Any]) -> str:
    schemas: dict[str, Any] = spec.get("components", {}).get("schemas", {})
    paths: dict[str, Any] = spec.get("paths", {})

    out: list[str] = [
        "/* eslint-disable */",
        "// AUTO-GENERATED BY scripts/generate_openapi_client.py — DO NOT EDIT MANUALLY.",
        "// Regenerate via `make generate-client`; verified in CI via `make check-client`.",
        "",
        "export interface ApiErrorEnvelope {",
        "  error: {",
        "    code: string;",
        "    message: string;",
        "    correlation_id: string;",
        "    details?: any;",
        "  };",
        "}",
        "",
        "export class SentinelApiError extends Error {",
        "  public readonly status: number;",
        "  public readonly code: string;",
        "  public readonly correlationId: string;",
        "  public readonly details?: any;",
        "",
        "  constructor(status: number, code: string, message: string, correlationId: string, details?: any) {",
        "    super(message);",
        "    this.name = 'SentinelApiError';",
        "    this.status = status;",
        "    this.code = code;",
        "    this.correlationId = correlationId;",
        "    this.details = details;",
        "  }",
        "}",
        "",
    ]

    for schema_name in sorted(schemas.keys()):
        ts_name = _sanitize_ts_identifier(schema_name)
        ts_body = _schema_to_ts(schemas[schema_name], schemas, indent=0)
        if ts_body.startswith("{"):
            out.append(f"export interface {ts_name} {ts_body}")
        else:
            out.append(f"export type {ts_name} = {ts_body};")
        out.append("")

    # Emit typed operation catalog so callers and tests can inspect every API route
    out.append("export const OPENAPI_PATHS = {")
    for route_path in sorted(paths.keys()):
        methods = sorted(
            m.upper()
            for m in paths[route_path].keys()
            if m.lower() in {"get", "post", "put", "patch", "delete"}
        )
        out.append(f"  {json.dumps(route_path)}: {json.dumps(methods)} as const,")
    out.append("} as const;")
    out.append("")

    out.extend(
        [
            "export function readCsrfCookie(): string | null {",
            "  if (typeof document === 'undefined') return null;",
            "  const match = document.cookie.match(/(?:^|;\\s*)sentinel_csrf=([^;]+)/);",
            "  return match ? decodeURIComponent(match[1]) : null;",
            "}",
            "",
            "let refreshPromise: Promise<boolean> | null = null;",
            "",
            "async function tryRefreshSession(): Promise<boolean> {",
            "  if (refreshPromise) return refreshPromise;",
            "  refreshPromise = (async () => {",
            "    try {",
            "      const csrf = readCsrfCookie();",
            "      const headers: Record<string, string> = {};",
            "      if (csrf) headers['X-CSRF-Token'] = csrf;",
            "      const res = await fetch('/api/v1/auth/refresh', {",
            "        method: 'POST',",
            "        credentials: 'include',",
            "        headers,",
            "      });",
            "      return res.ok;",
            "    } catch {",
            "      return false;",
            "    } finally {",
            "      refreshPromise = null;",
            "    }",
            "  })();",
            "  return refreshPromise;",
            "}",
            "",
            "export interface ApiRequestOptions extends Omit<RequestInit, 'body'> {",
            "  body?: any;",
            "  params?: Record<string, string | number | boolean | undefined | null>;",
            "  skipAuthRefresh?: boolean;",
            "}",
            "",
            "export async function apiRequest<T = any>(path: string, options: ApiRequestOptions = {}): Promise<T> {",
            "  const { body, params, skipAuthRefresh = false, headers: customHeaders, ...rest } = options;",
            "  const method = (rest.method || 'GET').toUpperCase();",
            "",
            "  let url = path.startsWith('/health') ? `/api${path}` : path;",
            "  if (params) {",
            "    const sp = new URLSearchParams();",
            "    for (const [k, v] of Object.entries(params)) {",
            "      if (v !== undefined && v !== null && v !== '') {",
            "        sp.set(k, String(v));",
            "      }",
            "    }",
            "    const qs = sp.toString();",
            "    if (qs) url += (url.includes('?') ? '&' : '?') + qs;",
            "  }",
            "",
            "  const buildHeaders = (): Headers => {",
            "    const h = new Headers(customHeaders || {});",
            "    if (!['GET', 'HEAD', 'OPTIONS'].includes(method)) {",
            "      const csrf = readCsrfCookie();",
            "      if (csrf && !h.has('X-CSRF-Token')) {",
            "        h.set('X-CSRF-Token', csrf);",
            "      }",
            "    }",
            "    if (body !== undefined && !(body instanceof FormData) && !h.has('Content-Type')) {",
            "      h.set('Content-Type', 'application/json');",
            "    }",
            "    return h;",
            "  };",
            "",
            "  const serializedBody =",
            "    body === undefined",
            "      ? undefined",
            "      : body instanceof FormData || typeof body === 'string'",
            "      ? body",
            "      : JSON.stringify(body);",
            "",
            "  let res = await fetch(url, {",
            "    ...rest,",
            "    method,",
            "    credentials: 'include',",
            "    headers: buildHeaders(),",
            "    body: serializedBody,",
            "  });",
            "",
            "  if (res.status === 401 && !skipAuthRefresh && !url.includes('/auth/login') && !url.includes('/auth/refresh')) {",
            "    const refreshed = await tryRefreshSession();",
            "    if (refreshed) {",
            "      res = await fetch(url, {",
            "        ...rest,",
            "        method,",
            "        credentials: 'include',",
            "        headers: buildHeaders(),",
            "        body: serializedBody,",
            "      });",
            "    }",
            "  }",
            "",
            "  if (!res.ok) {",
            "    let code = `HTTP_${res.status}`;",
            "    let message = res.statusText || 'Request failed';",
            "    let correlationId = res.headers.get('x-request-id') || '-';",
            "    let details: any = undefined;",
            "    try {",
            "      const errJson = (await res.json()) as Partial<ApiErrorEnvelope>;",
            "      if (errJson?.error) {",
            "        code = errJson.error.code || code;",
            "        message = errJson.error.message || message;",
            "        correlationId = errJson.error.correlation_id || correlationId;",
            "        details = errJson.error.details;",
            "      }",
            "    } catch {",
            "      // Non-JSON error response",
            "    }",
            "    throw new SentinelApiError(res.status, code, message, correlationId, details);",
            "  }",
            "",
            "  if (res.status === 204) {",
            "    return undefined as T;",
            "  }",
            "  const ct = res.headers.get('content-type') || '';",
            "  if (ct.includes('application/json')) {",
            "    return (await res.json()) as T;",
            "  }",
            "  return (await res.blob()) as unknown as T;",
            "}",
            "",
        ]
    )

    return "\n".join(out)


def main() -> int:
    check_only = "--check" in sys.argv
    app = create_app()
    spec = app.openapi()

    openapi_json_str = json.dumps(spec, indent=2, sort_keys=True) + "\n"
    ts_sdk_str = render_typescript_sdk(spec)

    if check_only:
        if not OPENAPI_OUT.exists() or not TS_OUT.exists():
            print("[check-client] FAILED: Generated OpenAPI client files do not exist.", file=sys.stderr)
            return 1
        current_json = OPENAPI_OUT.read_text(encoding="utf-8")
        current_ts = TS_OUT.read_text(encoding="utf-8")
        if current_json != openapi_json_str or current_ts != ts_sdk_str:
            print(
                "[check-client] FAILED: OpenAPI client is out of date. Run `make generate-client`.",
                file=sys.stderr,
            )
            return 1
        print("[check-client] OK: Committed OpenAPI spec and TypeScript client match FastAPI schema.")
        return 0

    OPENAPI_OUT.parent.mkdir(parents=True, exist_ok=True)
    OPENAPI_OUT.write_text(openapi_json_str, encoding="utf-8")
    TS_OUT.write_text(ts_sdk_str, encoding="utf-8")
    print(f"[generate-client] Wrote {OPENAPI_OUT.relative_to(ROOT)} and {TS_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

